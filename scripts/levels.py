def calc_suggested_shares(price, capital=None, positions=None):
    """计算单票建议买入股数(100股整数倍)与单笔成交金额。
    小资金默认将本金平均分配给每个目标持仓档位(如 1.5w / 3 = 5000元/只)。"""
    cap = capital or TOTAL_CAPITAL
    pos = positions or TARGET_POSITIONS
    alloc_money = cap / max(1, pos)
    if not price or price <= 0:
        return 0, 0.0
    shares = int(alloc_money // (price * 100)) * 100
    if shares == 0 and alloc_money >= price * 100:
        shares = 100
    est_amount = shares * price
    return shares, est_amount


def check_trade_plan(buy, stop, target, cost=None, rr_min=1.5, stop_max_pct=12.0):
    """交易计划体检 (专业风控, 2026-08-23 新增)。

    校验一个买入计划是否自洽、风险回报是否合格:
      - 自洽性: stop < buy < target (止损必须在买点之下, 目标必须在买点之上)
      - 成本口径: 若给 cost(实际成本), 目标必须高于 cost、止损必须低于 cost
        (典型案例: 开开实业 600272 成本 20.415, 目标 19.60 < 成本 → 计划自相矛盾)
      - R:R (风险回报比) = (target-buy)/(buy-stop), 应 >= rr_min (默认 1.5)
      - 单笔止损距离 (buy-stop)/buy 不应超过 stop_max_pct (小资金扛不住大止损)

    返回 {ok, rr, risk_pct, reward_pct, issues[], advice}
      ok=False 时 issues 非空且必须整改后才可建仓。
    """
    issues = []
    try:
        buy = float(buy); stop = float(stop); target = float(target)
    except (TypeError, ValueError):
        return {"ok": False, "rr": None, "risk_pct": None, "reward_pct": None,
                "issues": ["价位数据缺失, 无法校验"], "advice": "补齐买点/止损/目标后再评估"}
    if buy <= 0:
        return {"ok": False, "rr": None, "risk_pct": None, "reward_pct": None,
                "issues": ["买点价格无效"], "advice": "先确定入场参考价"}
    if stop and stop <= 0:
        issues.append("止损价无效")
    if target and target <= 0:
        issues.append("目标价无效")

    # 自洽性
    if stop and stop < buy:
        risk = buy - stop
    elif stop:
        issues.append(f"止损 {stop:.2f} 高于/等于买点 {buy:.2f} → 倒挂, 计划无效 (应 止损 < 买点)")
        risk = 0.0
    else:
        issues.append("缺少止损价, 无法控风险")
        risk = 0.0
    if target and target > buy:
        reward = target - buy
    elif target:
        issues.append(f"目标 {target:.2f} 低于/等于买点 {buy:.2f} → 目标无意义 (应 目标 > 买点)")
        reward = 0.0
    else:
        issues.append("缺少目标价")
        reward = 0.0

    # 成本口径 (持仓/加仓视角)
    if cost and cost > 0:
        if target and target <= cost:
            issues.append(f"目标价 {target:.2f} 低于成本 {cost:.2f} → 达标即亏损, 计划自相矛盾")
        if stop and stop >= cost:
            issues.append(f"止损价 {stop:.2f} 高于成本 {cost:.2f} → 止损线形同虚设(仍在成本上方)")

    # R:R 与止损距离
    rr = None
    risk_pct = None
    reward_pct = None
    if risk > 0 and reward > 0:
        rr = reward / risk
        risk_pct = risk / buy * 100
        reward_pct = reward / buy * 100
        if rr < rr_min - 1e-9:
            issues.append(f"风险回报比 R:R={rr:.2f} 低于 {rr_min} (止损{stop:.2f}~目标{target:.2f}), 赔率不划算")
        if risk_pct > stop_max_pct:
            issues.append(f"单笔止损距离 {risk_pct:.1f}% 过大 (> {stop_max_pct:.0f}%), 小资金回撤难控")

    advice = ("计划自洽, 可执行。" if not issues else "⚠️ 需整改: " + "; ".join(issues))
    return {"ok": not issues, "rr": rr, "risk_pct": risk_pct, "reward_pct": reward_pct,
            "issues": issues, "advice": advice}


def format_condition_order(code, name, buy_price=None, stop_price=None, target_price=None, capital=None, positions=None, cost=None):
    """生成面向手机券商 App (同花顺/华泰/银河等) 的一键条件单设置指引。"""
    shares, est_amt = calc_suggested_shares(buy_price or stop_price or 10.0, capital, positions)
    lines = [f"📱 【手机条件单设置指引】 {name}({code}) | 建议仓位: {shares}股 (约 ¥{est_amt:.0f})"]
    if buy_price and buy_price > 0:
        lines.append(f"  • 📥 买入条件单: 现价 <= {buy_price:.2f} 元 | 触发限价/市价买入 {shares} 股")
    if stop_price and stop_price > 0:
        risk_money = (buy_price - stop_price) * shares if buy_price and buy_price > stop_price else (10.0 - stop_price) * shares
        risk_pct_total = (risk_money / (capital or TOTAL_CAPITAL)) * 100 if risk_money > 0 else 0
        risk_str = f" (单笔预计亏损: -¥{risk_money:.0f}, 占本金 {risk_pct_total:.1f}%)" if risk_money > 0 else ""
        lines.append(f"  • 🛡️ 止损条件单: 现价 <= {stop_price:.2f} 元 | 自动全清/卖出 {shares} 股{risk_str}")
    if target_price and target_price > 0:
        lines.append(f"  • 🎯 止盈条件单: 现价 >= {target_price:.2f} 元 (或冲高回落 1.5%) | 减仓半数/清仓")
    # 计划体检 (专业风控): 有买点+止损+目标才校验; 严重问题直接标注
    plan = check_trade_plan(buy_price, stop_price, target_price, cost=cost)
    if plan["rr"] is not None:
        lines.append(f"  • ⚖️ R:R {plan['rr']:.2f} : 1 | 止损空间 {plan['risk_pct']:.1f}% | 目标空间 {plan['reward_pct']:.1f}%")
    if plan["issues"]:
        lines.append(f"  • 🚫 计划体检未通过: {'; '.join(plan['issues'])}")
    return "\n".join(lines)